const TABLES = { en: EN, fa: FA };

export function normalizeLang(value) {
  return value === 'fa' ? 'fa' : 'en';
}

export function getLang() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored) return normalizeLang(stored);
  } catch (e) {}
  return 'fa';
}

export function setLang(value) {
  const next = normalizeLang(value);
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch (e) {}
  return next;
}

export function isRtl() {
  return getLang() === 'fa';
}

export function t(key, vars = {}) {
  const table = TABLES[getLang()] || EN;
  let value = table[key];
  if (value === undefined) value = EN[key];
  if (value === undefined) return key;
  return String(value).replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

export function languageName() {
  return getLang() === 'fa' ? 'فارسی' : 'English';
}

export function toggleLang() {
  return setLang(getLang() === 'fa' ? 'en' : 'fa');
}

export function applyDocumentLang() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.documentElement.dataset.lang = lang;
}

export function localize(root = document) {
  applyDocumentLang();
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    if (key) node.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((node) => {
    const key = node.getAttribute('data-i18n-html');
    if (key) node.innerHTML = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.getAttribute('data-i18n-placeholder');
    if (key) node.setAttribute('placeholder', t(key));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((node) => {
    const key = node.getAttribute('data-i18n-title');
    if (key) node.setAttribute('title', t(key));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    const key = node.getAttribute('data-i18n-aria');
    if (key) node.setAttribute('aria-label', t(key));
  });
}
